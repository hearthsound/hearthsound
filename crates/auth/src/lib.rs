//! Accounts and their credentials.
//!
//! This crate owns the tables that say who a request is: `users`,
//! `api_keys`, `app_passwords`, the per-user overrides in `user_settings`, and
//! the per-user acquisition limits in `user_quotas`. It is the only crate that
//! hashes a password, compares a secret in constant time, or decrypts an app
//! password.
//!
//! The credentials follow the design's storage rules:
//!
//! - an account password is stored as an Argon2id hash and never reversibly
//!   ([`hash_password`], [`verify_password`], [`Users`]);
//! - an API key is shown once, stored as its SHA-256 hash and a short prefix,
//!   and revoked per key ([`ApiKeys`]);
//! - an app password is generated by the server, sealed with the AES-256-GCM
//!   secret box because Subsonic token authentication needs the plaintext
//!   secret back, and revoked per app password ([`AppPasswords`]);
//! - a setting a user may override shadows the server value for that user only
//!   ([`UserSettings`]).
//!
//! [`Authenticator`] ties them together: it turns the `u`, `p`, `t`, `s` and
//! `apiKey` parameters of a `/rest` request into a [`Principal`] or a typed
//! [`AuthenticationError`] carrying the Subsonic error code. It also signs a web
//! client in with its account password and resolves the `Authorization: Bearer`
//! key of the native API, and [`Sessions`] issues and resolves the cookie
//! sessions that client keeps. [`SetupGate`] holds the one-time token the
//! first-run setup link carries while the server has no account.
//!
//! Library code takes plain values and reads [`hearthsound_config::SettingsStore`]
//! snapshots handed to it by the composition root; it never reads the process
//! environment or a config file itself.
